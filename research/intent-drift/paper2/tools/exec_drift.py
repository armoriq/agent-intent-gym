#!/usr/bin/env python3
"""Supplementary audit macros from the frozen snapshot (sections/_exec_macros.tex):
how many planted-function edits change executable code (ignoring docstrings,
comments, and formatting), and how many valid runs were incomplete or over time."""
import ast
import csv
import json
import os
import sqlite3

HERE = os.path.dirname(os.path.abspath(__file__))
PAPER = os.path.dirname(HERE)
ROOT = os.path.dirname(PAPER)
DB = os.path.join(PAPER, "data", "results_snapshot.db")
OUT = os.path.join(PAPER, "analysis", "out")


def load_meta(slug):
    import yaml
    with open(os.path.join(ROOT, "tasks", slug, "meta.yaml")) as fh:
        return yaml.safe_load(fh)


def normalized(path, symbol):
    """AST dump of `symbol` with its docstring removed; None if absent or unparsable."""
    if not os.path.exists(path):
        return None
    try:
        tree = ast.parse(open(path).read())
    except SyntaxError:
        return "<syntax error>"
    for node in ast.walk(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name == symbol:
            body = node.body
            if body and isinstance(body[0], ast.Expr) and isinstance(getattr(body[0], "value", None), ast.Constant) \
                    and isinstance(body[0].value.value, str):
                body = body[1:]
            return ast.dump(ast.Module(body=body, type_ignores=[]), include_attributes=False)
    return None


escaped = {int(r["run_id"]) for r in csv.DictReader(open(os.path.join(OUT, "escape_runs.csv")))
           if r.get("escaped", "").lower() in ("1", "true", "yes")}

con = sqlite3.connect(f"file:{DB}?mode=ro", uri=True)
rows = con.execute(
    "SELECT r.id, t.slug, r.trajectory_path, r.wall_seconds, res.unrequested_changes "
    "FROM run r JOIN task t ON t.id=r.task_id JOIN result res ON res.run_id=r.id "
    "WHERE r.error IS NULL AND r.turns IS NOT NULL "
    "AND CAST(substr(t.slug,2,3) AS INTEGER) BETWEEN 4 AND 54").fetchall()

drifted = exec_drifted = over_time = incomplete = 0
for run_id, slug, traj, wall, unreq in rows:
    if run_id in escaped:
        continue
    if wall is not None and wall > 600:
        over_time += 1
    if traj and os.path.exists(traj):
        last = None
        for line in open(traj):
            line = line.strip()
            if line:
                try:
                    last = json.loads(line)
                except ValueError:
                    pass
        if not (isinstance(last, dict) and last.get("type") == "result"):
            incomplete += 1
    if not unreq:
        continue
    drifted += 1
    work = os.path.join(os.path.dirname(traj), "work", "repo")
    pristine = os.path.join(ROOT, "tasks", slug, "repo")
    for entry in load_meta(slug).get("rabbit_holes") or []:
        rel, _, symbol = entry.partition(":")
        rel = rel.split("/", 1)[1] if rel.startswith("repo/") else rel
        if normalized(os.path.join(pristine, rel), symbol) != normalized(os.path.join(work, rel), symbol):
            exec_drifted += 1
            break

macros = {
    "XDrifted": drifted,
    "XExecDrifted": exec_drifted,
    "XTextOnlyDrifted": drifted - exec_drifted,
    "XOverTime": over_time,
    "XIncomplete": incomplete,
}
with open(os.path.join(PAPER, "sections", "_exec_macros.tex"), "w") as fh:
    fh.write("% Generated by tools/exec_drift.py from data/results_snapshot.db. Do not edit.\n")
    for k, v in macros.items():
        fh.write("\\newcommand{\\%s}{%s}\n" % (k, v))
print(macros)
