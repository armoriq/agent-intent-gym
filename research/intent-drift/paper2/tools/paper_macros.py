#!/usr/bin/env python3
"""Write sections/_paper_macros.tex: short macros for the paper text, derived from
the analysis CSVs in analysis/out. The non-escaped (NoEsc) population is primary."""
import csv
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT_DIR = os.path.join(os.path.dirname(HERE), "analysis", "out")
GEN = {"gen-1": "Gone", "gen-2": "Gtwo"}
RUNG = {"scoped": "Scoped", "loose": "Loose", "realistic_vague": "Vague"}


def rows(name):
    with open(os.path.join(OUT_DIR, name)) as fh:
        return list(csv.DictReader(fh))


def frac(k, n):
    return f"{int(float(k))} of {int(float(n))}"


def pct(x):
    return f"{100 * float(x):.1f}\\%"


def p_fmt(p, floor):
    p = float(p)
    return "$p<10^{-4}$" if abs(p - floor) < 1e-12 else f"$p={p:.2g}$"


macros = {}
for r in rows("scope_generation.csv"):
    if r["population"] != "NoEsc" or r["rung"] not in RUNG:
        continue
    stem = "Sc" + GEN[r["generation"]] + RUNG[r["rung"]]
    for key, name in [("planted_drifted", "Planted"), ("any_out_of_scope", "AnyOos"),
                      ("test_edited", "TestEdit"), ("other_out_of_scope", "OtherOos")]:
        macros[f"{stem}{name}Frac"] = frac(r[f"{key}_count"], r[f"{key}_n"])
        macros[f"{stem}{name}Pct"] = pct(r[f"{key}_rate"])
        macros[f"{stem}{name}CiLowPct"] = pct(r[f"{key}_ci_low"])
        macros[f"{stem}{name}CiHighPct"] = pct(r[f"{key}_ci_high"])

for r in rows("observed_exposure.csv"):
    if r["population"] != "NoEsc" or r["rung"] not in RUNG:
        continue
    stem = "Ex" + GEN[r["generation"]] + RUNG[r["rung"]]
    macros[f"{stem}ReadFrac"] = frac(r["exposed_non_target_any_count"], r["exposed_non_target_any_n"])
    macros[f"{stem}ReadPct"] = pct(r["exposed_non_target_any_rate"])
    macros[f"{stem}ReadDriftFrac"] = frac(r["drift_among_non_target_exposed_count"], r["non_target_exposed_n"])
    macros[f"{stem}MeanFilesRead"] = f"{float(r['mean_rabbit_files_read']):.1f}"

for r in rows("exposure_noesc.csv"):
    if r["scope"] != "generation":
        continue
    stem = "Tc" + GEN[r["generation"]]
    macros[f"{stem}Scoped"] = f"{float(r['scoped_tool_calls']):.1f}"
    macros[f"{stem}Vague"] = f"{float(r['vague_tool_calls']):.1f}"
    macros[f"{stem}Diff"] = f"{float(r['tool_call_difference']):.1f}"
    macros[f"{stem}DiffCiLow"] = f"{float(r['tool_call_difference_ci_low']):.1f}"
    macros[f"{stem}DiffCiHigh"] = f"{float(r['tool_call_difference_ci_high']):.1f}"
    macros[f"{stem}Pairs"] = str(int(float(r["n_pairs"])))

for r in rows("overall_tests_noesc.csv"):
    stem = "Q" + {"all": "All", **GEN}[r["generation"]]
    q = float(r["statistic_q"])
    macros[f"{stem}Stat"] = str(int(q)) if q.is_integer() else f"{q:.1f}"
    macros[f"{stem}P"] = p_fmt(r["p_value"], 1 / (int(r["permutations"]) + 1))
    macros[f"{stem}Blocks"] = str(int(float(r["n_blocks"])))

for r in rows("disagreement_noesc.csv"):
    if r["scope"] == "all":
        macros["DgDrifted"] = r["drifted"]
        macros["DgDriftedHiddenPass"] = r["drifted_intent_pass"]
        macros["DgDriftedHiddenFail"] = r["drifted_intent_fail"]
        macros["DgN"] = r["n"]


for r in rows("ladder_generation_noesc.csv"):
    if r["rung"] not in RUNG:
        continue
    stem = "Lg" + GEN[r["generation"]] + RUNG[r["rung"]]
    macros[f"{stem}N"] = str(int(float(r["n"])))
    macros[f"{stem}HiddenPassPct"] = pct(r["intent_pass_rate"])
    macros[f"{stem}VisiblePassPct"] = pct(r["visible_pass_rate"])
    macros[f"{stem}PassGapPct"] = f"{100 * (float(r['visible_pass_rate']) - float(r['intent_pass_rate'])):.1f}"


esc = {}
for r in rows("escape_summary.csv"):
    esc[r["arm"]] = esc.get(r["arm"], 0) + int(r["escaped_count"])
cov_lines = ["\\begin{tabular}{@{}llrrrrr@{}}", "\\toprule",
             "Gen. & Arm & Attempted & Invalid & Valid & Escaped & Tasks covered \\\\", "\\midrule"]
prev = None
for r in rows("coverage.csv"):
    g = r["generation"][-1]
    if prev and g != prev:
        cov_lines.append("\\midrule")
    prev = g
    if r["arm"] == "g2-gemini-3.8":
        for k in ("attempted", "invalid", "null_turns", "valid", "tasks_covered"):
            macros["GemEight" + k.title().replace("_", "")] = r[k]
        macros["GemEightEscaped"] = str(esc.get(r["arm"], 0))
    cov_lines.append(f"{g} & {r['label']} & {r['attempted']} & {r['invalid']} & {r['valid']} & "
                     f"{esc.get(r['arm'], 0)} & {r['tasks_covered']} of 51 \\\\")
cov_lines += ["\\bottomrule", "\\end{tabular}"]
with open(os.path.join(os.path.dirname(HERE), "sections", "_coverage_table.tex"), "w") as fh:
    fh.write("\n".join(cov_lines) + "\n")

with open(os.path.join(os.path.dirname(HERE), "sections", "_paper_macros.tex"), "w") as fh:
    fh.write("% Generated by tools/paper_macros.py from analysis/out. Do not edit.\n")
    for k in sorted(macros):
        fh.write("\\newcommand{\\%s}{%s}\n" % (k, macros[k]))
print(f"wrote {len(macros)} macros")
