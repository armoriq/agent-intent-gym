#!/usr/bin/env python3
"""Generate the benchmark suite manifest from the task set.

Turns the lab-style suite card into a real registry: three domain benchmarks
defined by task membership (read live from tasks/*/meta.yaml via variant_group),
plus three measurement axes scored over those same tasks. Membership is derived,
not hand-listed, so the manifest cannot drift from the tasks on disk.

Output: suites/registry.yaml
Usage:  python3 harness/build_suite.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TASKS = os.path.join(ROOT, "tasks")
OUTDIR = os.path.join(ROOT, "suites")
OUT = os.path.join(OUTDIR, "registry.yaml")
sys.path.insert(0, HERE)
from run import load_meta  # noqa: E402

SUITE = "IntentBench"

# variant_group -> domain benchmark. Groups not listed here are seed tasks.
CORE = ["percentile", "pagination", "money", "backoff", "slug", "cache", "histogram"]
ALGO = ["median", "grade", "bisect", "mavg", "hms", "rank"]
SWE = ["config", "flags", "semver", "query"]
GROUP_SUITE = {g: "core" for g in CORE}
GROUP_SUITE.update({g: "algo" for g in ALGO})
GROUP_SUITE.update({g: "swe" for g in SWE})

DOMAIN_SUITES = {
    "core": ("Bug fixing", f"{SUITE}-Core 1.0",
             "Applied numeric and logic bugs in small real-world helpers."),
    "algo": ("Algorithmic reasoning", f"{SUITE}-Algo 1.0",
             "Pure-algorithmic off-by-one and boundary bugs."),
    "swe": ("Agentic coding", f"{SUITE}-SWE 1.0",
            "Broader software: config, CLI, versioning, URL building."),
}

AXES = [
    ("Instruction following", f"{SUITE}-Ladder 1.0",
     "Same repo and bug under three prompt phrasings (scoped / loose / vague); "
     "scores drift rate by rung. This is the suite's headline axis.",
     "prompt_variant in {scoped, loose, vague}"),
    ("Scope discipline", f"{SUITE}-Guard 1.0",
     "Counts out-of-scope symbols changed against four planted rabbit holes per "
     "task; a broken hidden test is a guarded-behaviour failure.",
     "unrequested_changes, intent_pass"),
    ("Cross-generation drift", f"{SUITE}-GenTrack 1.0",
     "The identical task set run across model generations to track whether "
     "fidelity moves with capability.",
     "arm generation (gen-1 vs gen-2)"),
]


def collect():
    domains = {"core": {}, "algo": {}, "swe": {}}
    seeds = []
    for slug in sorted(os.listdir(TASKS)):
        if not os.path.isdir(os.path.join(TASKS, slug)):
            continue
        m = load_meta(slug) or {}
        g = m.get("variant_group")
        suite = GROUP_SUITE.get(g)
        if suite is None:
            seeds.append(slug)
            continue
        domains[suite].setdefault(g, []).append((slug, m.get("prompt_variant")))
    return domains, seeds


def yq(s):
    return '"%s"' % s.replace('"', '\\"')


def build():
    domains, seeds = collect()
    os.makedirs(OUTDIR, exist_ok=True)
    L = []
    L.append("# IntentBench suite registry. Generated by harness/build_suite.py;")
    L.append("# task membership is derived from tasks/*/meta.yaml (variant_group).")
    L.append("# Do not hand-edit membership; re-run the generator.")
    L.append("suite: %s" % yq(SUITE))
    L.append("tagline: %s" % yq("Does the agent do the one thing asked, and "
                                "nothing else? An intent-fidelity suite."))
    L.append("")
    L.append("domain_benchmarks:")
    for key in ("swe", "algo", "core"):
        area, name, desc = DOMAIN_SUITES[key]
        groups = domains[key]
        n_tasks = sum(len(v) for v in groups.values())
        L.append("  - id: %s" % key)
        L.append("    area: %s" % yq(area))
        L.append("    name: %s" % yq(name))
        L.append("    description: %s" % yq(desc))
        L.append("    domains: %d" % len(groups))
        L.append("    tasks: %d" % n_tasks)
        L.append("    members:")
        for g in sorted(groups):
            slugs = ", ".join(s for s, _ in sorted(groups[g]))
            L.append("      %s: [%s]" % (g, slugs))
    L.append("")
    L.append("measurement_axes:")
    for area, name, desc, scored in AXES:
        L.append("  - area: %s" % yq(area))
        L.append("    name: %s" % yq(name))
        L.append("    description: %s" % yq(desc))
        L.append("    scored_over: all domain_benchmarks")
        L.append("    signal: %s" % yq(scored))
    L.append("")
    L.append("seed_tasks: [%s]" % ", ".join(seeds))
    L.append("")
    total = sum(sum(len(v) for v in domains[k].values()) for k in domains)
    L.append("totals:")
    L.append("  domain_benchmarks: 3")
    L.append("  measurement_axes: 3")
    L.append("  ladder_tasks: %d" % total)
    L.append("  seed_tasks: %d" % len(seeds))
    L.append("  all_tasks: %d" % (total + len(seeds)))
    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", OUT)
    for key in ("swe", "algo", "core"):
        area, name, _ = DOMAIN_SUITES[key]
        groups = domains[key]
        print("  %-22s %-18s %d domains / %d tasks"
              % (name, "(" + area + ")", len(groups),
                 sum(len(v) for v in groups.values())))
    print("  seeds:", ", ".join(seeds))


if __name__ == "__main__":
    build()
