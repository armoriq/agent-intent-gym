#!/usr/bin/env python3
"""Extract the per-domain intent contracts the benchmark already encodes.

Each scoped task states exactly one allowed change (in_scope) and the concrete
symbols that must not change (rabbit_holes, as file:function, plus prose
out_of_scope). That is precisely the intent an Armor policy would enforce at
runtime: permit the one edit, deny the rest. This writes those contracts out in
a policy-neutral form so the Armor policy files and the projection can be built
on real task data, not invented scopes.

Output: armor-intent/intents.yaml
Usage:  python3 harness/gen_armor_intent.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
TASKS = os.path.join(ROOT, "tasks")
OUT = os.path.join(ROOT, "armor-intent", "intents.yaml")
sys.path.insert(0, HERE)
from run import load_meta  # noqa: E402
import intent_data as D  # noqa: E402


def scoped_bases():
    """Every scoped ladder base (has in_scope + rabbit_holes), grouped by suite."""
    suites = {"core": [], "algo": [], "swe": []}
    # reuse the registry's group->suite mapping
    import build_suite as bs
    for slug in sorted(os.listdir(TASKS)):
        m = load_meta(slug) or {}
        if m.get("prompt_variant") != "scoped":
            continue
        s = bs.GROUP_SUITE.get(m.get("variant_group"))
        if s:
            suites[s].append((slug, m))
    return suites


def q(s):
    return '"%s"' % str(s).replace('"', '\\"')


def build():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    suites = scoped_bases()
    L = []
    L.append("# Per-domain intent contracts, derived from tasks/*/meta.yaml.")
    L.append("# allow = the single change the developer asked for (in_scope).")
    L.append("# deny  = concrete symbols that must stay untouched (rabbit_holes).")
    L.append("# These feed the Armor policy files in policies/ and the projection.")
    L.append("# Generated by harness/gen_armor_intent.py; do not hand-edit.")
    L.append("suite: IntentBench")
    total = 0
    for key, label in (("swe", "IntentBench-SWE"), ("algo", "IntentBench-Algo"),
                       ("core", "IntentBench-Core")):
        L.append("")
        L.append("%s:" % key)
        for slug, m in suites[key]:
            total += 1
            allow = (m.get("in_scope") or ["(missing)"])[0]
            holes = m.get("rabbit_holes", [])
            # The single permitted target is the buggy function itself. By
            # construction one rabbit hole is its <module>:old_<fn> alias, so
            # stripping "old_" recovers the exact file:function to permit.
            allow_target = "(unknown)"
            for h in holes:
                if ":old_" in h:
                    allow_target = h.replace(":old_", ":", 1)
                    break
            L.append("  - task: %s" % slug)
            L.append("    domain: %s" % q(m.get("variant_group")))
            L.append("    intent: %s" % q(allow))
            L.append("    allow_edit: %s" % allow_target)
            L.append("    deny_edit:")
            for sym in holes:
                L.append("      - %s" % sym)
            L.append("    out_of_scope_notes: %d" % len(m.get("out_of_scope", [])))
    L.insert(6, "domains: %d" % total)
    with open(OUT, "w") as f:
        f.write("\n".join(L) + "\n")
    print("wrote", OUT, "(%d domain contracts)" % total)


if __name__ == "__main__":
    build()
